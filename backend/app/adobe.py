"""Local simulation of the visual and the post. Moment is not integrated with Adobe.

Nothing contacts Adobe: no network calls, no credentials. Visuals are local SVG
placeholders (or ``ADOBE_MOCK_IMAGE_URL``) and "posts" exist only as the values
these functions return.

This module is the integration point: a real version would generate the visual
with Adobe Firefly in ``generate_visual`` and create and update the post with
Adobe Express in ``create_post`` and ``update_post``, keeping the same signatures.

Optional environment variables:
- ``ADOBE_MOCK_IMAGE_URL``: image URL to use instead of the SVG placeholder.
- ``ADOBE_MOCK_LATENCY_S``: simulated delay per call in seconds (default 0).
  It blocks with ``time.sleep``, so call these functions from a sync endpoint
  or a worker thread, not directly from async code.
"""

import base64
import hashlib
import html
import os
import textwrap
import time
from dataclasses import dataclass, replace

IMAGE_URL_ENV = "ADOBE_MOCK_IMAGE_URL"
REVISED_IMAGE_URL_ENV = "ADOBE_MOCK_REVISED_IMAGE_URL"  # the visual after review (apply)
LATENCY_ENV = "ADOBE_MOCK_LATENCY_S"

# Longer delays count as invalid: they would only hang the demo. The limit
# matches the default 15s timeout for external calls in CLAUDE.md.
MAX_LATENCY_S = 15.0

# The real Express home page. It does NOT contain the mock post, because no post
# is ever created in Express.
EXPRESS_HOME_URL = "https://new.express.adobe.com/"

SVG_SIZE = 1080
WRAP_WIDTH_CHARS = 28
MAX_TEXT_LINES = 8
LINE_HEIGHT_PX = 72
BLANK_PROMPT_TEXT = "Visual preview"
MOCK_LABEL = "Mock visual - not generated by Adobe Firefly"


@dataclass(frozen=True)
class Visual:
    image_url: str
    prompt: str
    is_mock: bool = True


@dataclass(frozen=True)
class ExpressPost:
    doc_id: str
    caption: str
    image_url: str
    version: int
    url: str
    is_mock: bool = True


def generate_visual(prompt: str) -> Visual:
    """Return a placeholder visual. The same prompt gives the same output."""
    _simulate_latency()
    override = os.environ.get(IMAGE_URL_ENV, "").strip()
    image_url = override or _svg_data_url(prompt)
    return Visual(image_url=image_url, prompt=prompt)


def revised_visual(prompt: str) -> Visual | None:
    """The visual after the review, as if Firefly regenerated it from the reviewed prompt.

    Returns the image in ``ADOBE_MOCK_REVISED_IMAGE_URL``, or None when it isn't set
    (then the post keeps its first visual unless the visual prompt changed).
    """
    revised = os.environ.get(REVISED_IMAGE_URL_ENV, "").strip()
    if not revised:
        return None
    _simulate_latency()
    return Visual(image_url=revised, prompt=prompt)


def create_post(caption: str, image_url: str) -> ExpressPost:
    """Return a mock post at version 1. Nothing is created in Express."""
    _simulate_latency()
    # The separator keeps ("ab", "c") and ("a", "bc") from sharing a doc_id.
    short_hash = _digest(f"{caption}\0{image_url}").hex()[:12]
    return ExpressPost(
        doc_id=f"mock-{short_hash}",
        caption=caption,
        image_url=image_url,
        version=1,
        url=EXPRESS_HOME_URL,
    )


def update_post(
    post: ExpressPost, caption: str | None = None, image_url: str | None = None
) -> ExpressPost:
    """Return a copy with the supplied fields changed and the version bumped."""
    _simulate_latency()
    return replace(
        post,
        caption=post.caption if caption is None else caption,
        image_url=post.image_url if image_url is None else image_url,
        version=post.version + 1,
    )


def _simulate_latency() -> None:
    delay = _latency_seconds()
    if delay > 0:
        time.sleep(delay)


def _latency_seconds() -> float:
    try:
        value = float(os.environ.get(LATENCY_ENV, ""))
    except ValueError:
        return 0.0
    # This range check also rejects nan and inf, which time.sleep would raise on.
    return value if 0 < value <= MAX_LATENCY_S else 0.0


def _digest(text: str) -> bytes:
    # surrogatepass: scraped text can hold lone surrogates, which must not raise.
    return hashlib.sha256(text.encode("utf-8", "surrogatepass")).digest()


def _svg_data_url(prompt: str) -> str:
    encoded = base64.b64encode(_render_svg(prompt).encode("utf-8")).decode("ascii")
    return f"data:image/svg+xml;base64,{encoded}"


def _render_svg(prompt: str) -> str:
    start, end = _gradient_colors(prompt)
    lines = _prompt_lines(prompt)
    first_y = SVG_SIZE // 2 - (len(lines) - 1) * LINE_HEIGHT_PX // 2
    text_rows = "".join(
        f'<text x="540" y="{first_y + index * LINE_HEIGHT_PX}" font-size="56">'
        f"{html.escape(line)}</text>"
        for index, line in enumerate(lines)
    )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" '
        f'width="{SVG_SIZE}" height="{SVG_SIZE}" '
        f'viewBox="0 0 {SVG_SIZE} {SVG_SIZE}">'
        '<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{start}"/>'
        f'<stop offset="1" stop-color="{end}"/>'
        "</linearGradient></defs>"
        f'<rect width="{SVG_SIZE}" height="{SVG_SIZE}" fill="url(#bg)"/>'
        '<g fill="#ffffff" text-anchor="middle" '
        'font-family="Arial, Helvetica, sans-serif">'
        f"{text_rows}"
        f'<text x="540" y="1030" font-size="28">{MOCK_LABEL}</text>'
        "</g></svg>"
    )


def _gradient_colors(prompt: str) -> tuple[str, str]:
    digest = _digest(prompt)
    return _dark_color(digest[:3]), _dark_color(digest[3:6])


def _dark_color(channels: bytes) -> str:
    # Keep every channel dark so the white text stays readable.
    return "#" + "".join(f"{30 + channel % 100:02x}" for channel in channels)


def _prompt_lines(prompt: str) -> list[str]:
    # Wrap before escaping, so that truncation can never cut an entity in half.
    text = " ".join(_replace_non_xml_chars(prompt).split())
    if not text:
        return [BLANK_PROMPT_TEXT]
    return textwrap.wrap(text, width=WRAP_WIDTH_CHARS, max_lines=MAX_TEXT_LINES, placeholder=" ...")


def _replace_non_xml_chars(text: str) -> str:
    # html.escape does not touch control characters, which make XML invalid.
    return "".join(char if _is_xml_char(char) else " " for char in text)


def _is_xml_char(char: str) -> bool:
    code = ord(char)
    return (
        code in (0x9, 0xA, 0xD)
        or 0x20 <= code <= 0xD7FF
        or 0xE000 <= code <= 0xFFFD
        or 0x10000 <= code <= 0x10FFFF
    )
